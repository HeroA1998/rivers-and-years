Object.assign(NPCS, FIG);

const figIn = id => ad() >= FIG[id].years[0] && ad() <= FIG[id].years[1];
const figMet = id => !!(S.npcs[id] && S.npcs[id].met);
const figReady = id => { const n = npc(id); return n.stage < 3 && n.fav >= STAGE_TH[n.stage]; };
// 還沒認識、而且人就在這座城（山）的人物
const figMeetable = s => { const c = Object.keys(FIG).filter(id => !figMet(id) && figIn(id) && FIG[id].loc === s.loc); return c.length ? pick(c) : undefined; };
// 已認識的人物：人在此地，或好感夠了特地來找你
const figVisitable = s => {
  const gap = today() - (s.flags.lastFig || -999), met = Object.keys(FIG).filter(id => figMet(id) && figIn(id));
  const here = met.filter(id => FIG[id].loc === s.loc);
  // 同一地有好幾位時，先遇到「有心結待解」的人，其次隨機，不會永遠只遇到同一個
  if (here.length && gap > 30) return here.filter(figReady)[0] || pick(here);
  return met.filter(id => s.npcs[id].fav >= 15 && gap > 75).sort((x, y) => (figReady(y) - figReady(x)) || (s.npcs[y].fav - s.npcs[x].fav))[0];
};

