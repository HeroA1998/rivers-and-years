/* ---------- 運作 ---------- */
const hStart = h => absDay(h.y, h.m, h.d || 1);
const hEnd = h => hStart(h) + (h.span || 1);
function histInit() {
  S.hist = S.hist || {};
  const t = today();
  for (const h of HIST) if (!S.hist[h.id] && hEnd(h) <= t) S.hist[h.id] = 'past';
}
// 每過一天：錯過的事件化為傳聞
function histTick() {
  if (!S.hist) histInit();
  const t = today();
  for (const h of HIST) {
    if (S.hist[h.id]) continue;
    if (!h.loc && t >= hStart(h)) hear(h);
    else if (h.loc && t >= hEnd(h)) hear(h);
  }
}
function hear(h) {
  S.hist[h.id] = 'heard';
  log(`【江湖傳聞】${h.news}`);
  (S.journal = S.journal || []).push({ t: dateStr(), ch: '耳聞', s: h.news });
}
// 人在現場：親見
function histDue() {
  if (!S.hist) histInit();
  const t = today();
  for (const h of HIST) {
    if (S.hist[h.id] || !h.loc || !h.scene) continue;
    if (S.loc === h.loc && t >= hStart(h) && t < hEnd(h)) {
      S.hist[h.id] = 'seen';
      (S.journal = S.journal || []).push({ t: dateStr(), ch: '親見', s: h.news });
      return Object.assign({ type: '歷史', art: h.art || LOCS[h.loc].art }, h.scene(S));
    }
  }
  return null;
}
// 風聞：即將發生、已有風聲的事
function histRumors(days = 400, any = false) {
  if (!S.hist) histInit();
  const t = today(), known = S.flags.heardOf || {};
  return HIST.filter(h => h.loc && h.scene && !S.hist[h.id] && (any || known[h.id] || hStart(h) - (h.lead || 0) <= t) && hStart(h) - t <= days)
    .map(h => ({ h, when: `${reign(h.y)}${MONTH_N[h.m]}${h.d ? cnDay(h.d) : ''}`, where: LOCS[h.loc].n, now: t >= hStart(h) }));
}
