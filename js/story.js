function storyDue() {
  if (S.story == null) { S.story = S.flags.savedWulin || S.flags.demonLord ? STORY.length : 0; S.journal = S.journal || []; }
  const st = STORY[S.story];
  if (!st || !st.ready(S)) return null;
  S.story++;
  S.journal.push({ t: dateStr(), ch: st.ch, s: st.log });
  return st.scene;
}
