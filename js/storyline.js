/* ---------- 運作 ---------- */
const lnDay = a => absDay(a[0], a[1], a[2] || 1);
const lnHist = n => n.at ? HIST.find(h => h.id === n.at) : null;
const lnLoc = n => n.at ? lnHist(n).loc : n.loc;
const lnFrom = n => n.at ? hStart(lnHist(n)) : lnDay(n.from);
const lnTo = n => n.at ? hEnd(lnHist(n)) : lnDay(n.to);
// 下一個還沒走到的段落；時間過了的，算作錯過
function lineNext() {
  if (!S || !S.line || !LINE[S.line]) return null;
  S.lineDone = S.lineDone || {};
  const t = today();
  for (const n of LINE[S.line]) {
    if (S.lineDone[n.id]) continue;
    if (t >= lnTo(n)) { S.lineDone[n.id] = 'missed'; continue; }
    return n;
  }
  return null;
}
const lineNow = () => { const n = lineNext(); return !!n && today() >= lnFrom(n) && (!lnLoc(n) || S.loc === lnLoc(n)); };
function lineDue() {
  if (!lineNow()) return null;
  const n = lineNext();
  S.lineDone[n.id] = 'seen';
  S.hist = S.hist || {};
  [n.at, ...(n.hist || [])].filter(Boolean).forEach(id => { S.hist[id] = 'seen'; });
  (S.journal = S.journal || []).push({ t: dateStr(), ch: LINE_N[S.line], s: n.title });
  if (n.after) n.after(S);
  if (n.end) log(`【${LINE_N[S.line]}】${n.title}之後，這條線走到了盡頭。`);
  const sc = n.scene(S);
  return Object.assign({ type: '主線', title: n.title, who: n.who, art: (LOCS[lnLoc(n) || S.loc] || LOCS.linan).art }, sc);
}
// 自訂段落快到了、人不在那裡：提醒動身（沿用年表場景的段落，由原本的「動身」事件負責）
function lineBridge() {
  const n = lineNext();
  if (!n || n.at || !n.loc || S.loc === n.loc) return null;
  const ask = S.flags.lineAsk = S.flags.lineAsk || {};
  if (ask[n.id]) return null;
  const t = today(), need = travelDays(n.loc), start = lnFrom(n), end = lnTo(n);
  if (start - t - need > 40 || t + need >= end) return null;
  ask[n.id] = 1;
  const go = () => {
    log(`自${LOCS[S.loc].n}啟程，行了${cnNum(need)}日，抵達${LOCS[n.loc].n}。`);
    S.loc = '_road'; advance(need); S.loc = n.loc;
    const wait = Math.max(0, start - today());
    if (wait) advanceSteps(wait);
    return `你一路趕到了${LOCS[n.loc].n}。`;
  };
  return { type: '主線', title: `動身：${LOCS[n.loc].n}`, who: n.who, art: LOCS[n.loc].art,
    text: `${n.call || ''}\n\n${LOCS[n.loc].n}離這裡還有 ${cnNum(need)} 日路程。`,
    choices: [{ s: 'g', t: `動身前往${LOCS[n.loc].n}`, go }, { s: 'n', t: '這次就算了', go: () => '你把這件事放下了。' }] };
}

