storyAppend = function (kind, text) { return _sgAppend(kind, text == null ? text : sgFix(String(text))); };
const _sgShow = showEvent;
showEvent = function (ev) {
  const r = _sgShow(ev), o = UI.ov;
  if (o && o.k === 'event') {
    if (o.title) o.title = sgFix(o.title);
    (o.choices || []).forEach(c => { c.t = sgFix(c.t); });
    if (o.pages) o.pages = o.pages.map(p => sgFix(String(p)));
    render();
  }
  return r;
};
